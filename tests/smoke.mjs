import {readFileSync,existsSync} from 'node:fs';
import assert from 'node:assert/strict';
const html=readFileSync('index.html','utf8');
const app=readFileSync('app.js','utf8');
const mobile=readFileSync('mobile.js','utf8');
const css=readFileSync('mobile.css','utf8');
for(const file of ['app.js','mobile.js','mobile.css','update_history.py','.github/workflows/weather.yml','.github/workflows/pages.yml']) assert.ok(existsSync(file),file);
for(const id of ['tempChart','windChart','rainChart','pressureChart','biteChart','historyChart','temp','feels','wind','gust','pressure','status','species','trip','compareMetric','diaryList']) {
 if(id==='diaryList')assert.ok(mobile.includes('id="diaryList"'),'diaryList generated by mobile.js');
 else assert.ok(html.includes('id="'+id+'"'),id);
}
assert.ok(html.includes('mobile.css')&&html.includes('mobile.js'),'Mobile assets wired');
assert.ok(css.includes('@media(orientation:landscape)'),'Landscape breakpoint');
assert.ok(css.includes('env(safe-area-inset-bottom)'),'iOS home indicator padding');
assert.ok(mobile.includes('navigator.geolocation.getCurrentPosition'),'GPS opt-in');
assert.ok(mobile.includes('localStorage'),'Offline catch diary');
assert.ok(app.includes('const a=c||{},stamp=a.time'),'Current time fix');
assert.ok(app.includes('wind_gusts_10m'),'Gusts');
console.log('SELIGER static smoke checks passed');
